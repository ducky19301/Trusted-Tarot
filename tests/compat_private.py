#!/usr/bin/env python3
"""Phone-size Chrome check of the private Compatibility tab + Settings (Appearance) on the box app.
run: /workspace/.tools-venv/bin/python tests/compat_private.py [http://127.0.0.1:8095] [shots-dir]
Point it at a TEST copy of the app (separate PORT/TAROT_DATA_DIR/TAROT_ENTRIES); it only saves to the browser's localStorage."""
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8095"
SHOTS = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parent / "shots" / "compat"); SHOTS.mkdir(parents=True, exist_ok=True)
fails = []
def check(c, m): print(("PASS " if c else "FAIL ") + m); (None if c else fails.append(m))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True, service_workers="block")
    ctx.route("https://fonts.googleapis.com/**", lambda r: r.abort()); ctx.route("https://fonts.gstatic.com/**", lambda r: r.abort())
    ctx.route("https://geocoding-api.open-meteo.com/**", lambda r: r.abort())
    page = ctx.new_page(); errs = []
    page.on("dialog", lambda d: d.accept())
    page.on("pageerror", lambda e: errs.append(str(e)))
    page.on("response", lambda r: errs.append("404 " + r.url) if r.status == 404 and "favicon" not in r.url else None)
    page.on("console", lambda m: errs.append(m.text) if m.type == "error" and "favicon" not in m.text and "ERR_FAILED" not in m.text else None)
    page.goto(URL + "/#today"); page.wait_for_timeout(1500)
    d = page.evaluate("Object.assign({}, document.documentElement.dataset)")
    check(d.get("theme") == "dark" and d.get("accent") == "gold" and d.get("stars") == "on", "default look is the original dark + gold + stars")
    page.screenshot(path=str(SHOTS / "01-today-default.png"))
    # Compatibility lives behind More on a phone
    page.click("#moreBtn"); page.wait_for_timeout(200)
    check(page.is_visible("#moreMenu [data-goto=compat]"), "More menu lists Compatibility")
    page.click("#moreMenu [data-goto=compat]"); page.wait_for_timeout(1200)
    check(page.is_visible("#cxNew"), "Compatibility home loads"); page.screenshot(path=str(SHOTS / "02-compat-home.png"))
    body = page.inner_text("#compatBody")
    check("Waiting for your OK" not in body and "Shared with you" not in body, "no invites / shared-with-you section")
    page.click("#cxNew"); page.wait_for_timeout(400)
    t = page.inner_text("#compatBody")
    check("Natalie" in t and "from your profile" in t and "Durango" in t and "10:36 PM" in t, "Person 1 is Natalie from the stored profile (Mar 7 1997, 10:36 PM, Durango)")
    check(page.query_selector("#a-name") is None, "Person 1 is locked (no editable fields)")
    check(page.query_selector("#cxConsent") is None, "no consent flow in the private app")
    page.screenshot(path=str(SHOTS / "03-compat-form.png"), full_page=True)
    page.click("#cxGo"); page.wait_for_timeout(300)
    check("name" in page.inner_text("#cxErr").lower(), "missing Person 2 shows an error")
    page.fill("#b-name", "Alex"); page.fill("#b-date", "1995-06-15"); page.check("#b-unk")
    page.fill("#b-place", "denver"); page.click("#b-look"); page.wait_for_timeout(300)
    check("Denver" in page.inner_text("#b-found"), "built-in birthplace lookup works offline")
    page.click("#cxGo"); page.wait_for_selector(".cx-story", timeout=15000); page.wait_for_timeout(500)
    check(page.is_visible(".cx-heat") and page.is_visible(".cx-wheel svg"), "result shows story, heatmap and bi-wheel")
    page.screenshot(path=str(SHOTS / "04-compat-result.png"))
    page.screenshot(path=str(SHOTS / "05-compat-result-full.png"), full_page=True)
    page.click(".cx-i >> nth=0"); page.wait_for_timeout(300)
    check(page.is_visible(".cx-sheet"), "(i) opens a how-it-was-worked-out sheet"); page.screenshot(path=str(SHOTS / "06-info-sheet.png")); page.keyboard.press("Escape")
    page.click("#cxDetails"); page.wait_for_timeout(300)
    check("Knowledge base sources" in page.inner_text(".cx-sheet"), "Details and sources sheet"); page.keyboard.press("Escape")
    page.click("#cxShare"); page.wait_for_timeout(300)
    sh = page.inner_text(".cx-sheet")
    check("1997" not in sh and "Durango" not in sh and "1995" not in sh and "22:36" not in sh, "share text has no birth details")
    check("friend" not in sh.lower() and "Send request" not in sh, "share sheet has no friend sending / links")
    page.screenshot(path=str(SHOTS / "07-share-sheet.png")); page.keyboard.press("Escape")
    page.click("#cxSave"); page.wait_for_timeout(400)
    saved = page.evaluate("JSON.parse(localStorage.getItem('tt-compat-me')||'[]')")
    check(len(saved) == 1 and saved[0]["b"] is None, "saved on this device; Person 2’s birth details not kept by default")
    page.click("#cxBack"); page.wait_for_timeout(300); page.click("#cxPriv"); page.wait_for_timeout(300)
    check("stay in this browser" in page.inner_text(".cx-sheet"), "privacy sheet explains private storage"); page.screenshot(path=str(SHOTS / "08-privacy.png")); page.keyboard.press("Escape")
    ctx.set_offline(True); page.evaluate("window.dispatchEvent(new Event('offline'))"); page.wait_for_timeout(300)
    check("offline" in page.inner_text("#compatBody").lower(), "offline note shows"); page.screenshot(path=str(SHOTS / "09-offline.png")); ctx.set_offline(False)
    # Settings → Appearance
    page.click("#tjGear"); page.wait_for_timeout(500)
    check(page.is_visible(".tj-modal") and "10:36 PM" in page.inner_text(".tj-modal"), "Settings opens with Appearance and My chart")
    page.screenshot(path=str(SHOTS / "10-settings.png"), full_page=False)
    page.click("[data-ap=theme][data-v=light]"); page.click("[data-ap=accent][data-v=teal]"); page.click("[data-ap=size][data-v=xl]"); page.wait_for_timeout(200)
    d = page.evaluate("Object.assign({}, document.documentElement.dataset)")
    check(d["theme"] == "light" and d["accent"] == "teal" and d["size"] == "xl", "theme / accent / text size apply right away")
    page.screenshot(path=str(SHOTS / "11-settings-light.png"))
    page.click("#st-close"); page.evaluate("location.hash='journal'"); page.wait_for_timeout(900); page.screenshot(path=str(SHOTS / "12-journal-light-teal-xl.png"))
    page.reload(); page.wait_for_timeout(1200)
    check(page.evaluate("document.documentElement.dataset.theme") == "light", "appearance survives a reload")
    page.click("#tjGear"); page.wait_for_timeout(300); page.click("#st-lookreset"); page.wait_for_timeout(200)
    d = page.evaluate("Object.assign({}, document.documentElement.dataset)")
    check(d["theme"] == "dark" and d["accent"] == "gold" and d["size"] == "m", "Reset to default restores the original look")
    page.click("#st-close"); page.evaluate("location.hash='journal'"); page.wait_for_timeout(900); page.screenshot(path=str(SHOTS / "13-journal-default.png"))
    # /auth/status and /social/* are answered by the password gate (:8091), not the bare app, so they 404 here (pre-existing)
    errs = [e for e in errs if "/auth/status" not in e and "/social/" not in e and "status of 404" not in e]
    check(not errs, "no console errors: " + "; ".join(errs[:5]))
    b.close()
print("all compat checks passed" if not fails else f"{len(fails)} FAILED"); sys.exit(1 if fails else 0)
